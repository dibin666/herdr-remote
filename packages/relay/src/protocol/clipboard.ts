// Clipboard forwarding between a window's terminal session and that window's
// own clipboard. The host shims the workstation's clipboard tools for each
// Herdr client; writes ride `clipboard_write` down to the window's local
// clipboard and reads go up as `clipboard_read`, answered by
// `clipboard_read_reply`. Herdr caps clipboard text at 1 MB itself, so the
// relay never needs to carry more.
//
// The wire types live here rather than in `messages.ts`, which imports them;
// every message is stream-addressed the same way `StreamAddressed` declares
// there — `clientId` first, `streamId` the same value — without this module
// importing the one that imports it.

/** The most clipboard text one message carries, in UTF-16 code units. */
export const CLIPBOARD_TEXT_MAX_CHARS = 1_000_000;

/** A clipboard read's correlation id: generated by the host, echoed back. */
export const CLIPBOARD_REQUEST_ID_MAX_CHARS = 64;

/**
 * Clipboard text the relay will carry, or null. Only real strings of a sane
 * length pass; anything else means the message is not a clipboard payload.
 */
export function sanitizeClipboardText(value: unknown): string | null {
  if (typeof value !== 'string' || value.length > CLIPBOARD_TEXT_MAX_CHARS) return null;
  return value;
}

/**
 * A request id the relay will carry, or null. Hosts generate short tokens;
 * longer or non-string values are rejected like an unknown stream.
 */
export function sanitizeClipboardRequestId(value: unknown): string | null {
  if (typeof value !== 'string' || value.length === 0) return null;
  if (value.length > CLIPBOARD_REQUEST_ID_MAX_CHARS) return null;
  return value;
}

/**
 * This window's answer to a `clipboard_read`: its own clipboard's text, or an
 * empty string when reading failed or the clipboard held no text. The relay
 * sends it on to this window's workstation, where the pending shim request
 * waits on the requestId.
 */
export interface ClientClipboardReadReplyMessage {
  type: 'clipboard_read_reply';
  requestId: string;
  text: string;
}

/**
 * This window's terminal session copied to the clipboard: Herdr on the
 * workstation ran a clipboard tool the connector shims, and the write lands
 * in this browser's own clipboard instead of the workstation's.
 */
export interface ServerClipboardWriteMessage {
  type: 'clipboard_write';
  text: string;
}

/**
 * This window's terminal session wants clipboard text: Herdr read a shimmed
 * clipboard tool. This window answers with `clipboard_read_reply`.
 */
export interface ServerClipboardReadMessage {
  type: 'clipboard_read';
  requestId: string;
}

/**
 * The Herdr client in this stream's PTY wrote to the clipboard through a
 * shimmed tool: the window behind the stream gets the text instead of the
 * workstation's own clipboard.
 */
export interface HostClipboardWriteMessage {
  type: 'clipboard_write';
  clientId?: string;
  streamId?: string;
  text: string;
}

/**
 * The Herdr client in this stream's PTY read a shimmed clipboard tool. The
 * window behind the stream answers with `clipboard_read_reply`, routed back
 * by requestId.
 */
export interface HostClipboardReadMessage {
  type: 'clipboard_read';
  clientId?: string;
  streamId?: string;
  requestId: string;
}

/**
 * The window's answer to its session's `clipboard_read`. The host matches
 * requestId to the shim call still waiting on its forwarding socket.
 */
export interface RelayClipboardReadReplyMessage {
  type: 'clipboard_read_reply';
  clientId?: string;
  streamId?: string;
  requestId: string;
  text: string;
}
