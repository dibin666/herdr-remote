// Browsing the directory a terminal session sits in, and pulling files out of
// it. A window asks for the listing, picks entries by name, then pulls the
// answer — one file, or a zip the host built — a slice at a time, the same way
// fonts move.
//
// The wire types live here rather than in `messages.ts`, which imports them;
// every message is stream-addressed the same way `StreamAddressed` declares
// there — `clientId` first, `streamId` the same value — without this module
// importing the one that imports it.
//
// Browser-safe: constants, validators and types only.

/** The most entries one `fs_list_response` may carry. */
export const FS_LIST_MAX_ENTRIES = 4096;

/** A slice of a download, before base64. The same size fonts use. */
export const FS_DOWNLOAD_CHUNK_BYTES = 256 * 1024;

/**
 * The most a whole download may be, zipped or not. Base64 grows it by a third
 * on the wire, but the browser assembles the decoded bytes, so the cap is on
 * what those bytes are — generous, still short of what a phone's tab survives.
 */
export const FS_DOWNLOAD_MAX_BYTES = 128 * 1024 * 1024;

/** The most names one `fs_download_request` may pick. */
export const FS_DOWNLOAD_MAX_NAMES = 1024;

/** The most bytes of a file a preview reads; bigger files arrive truncated. */
export const FS_PREVIEW_MAX_BYTES = 256 * 1024;

/** Longest entry name a listing or a download may carry, in characters. */
export const FS_NAME_MAX_CHARS = 255;

/** Longest working-directory path a list answer may carry, in characters. */
export const FS_CWD_MAX_CHARS = 4096;

/** A request id of any fs message: generated by the window, echoed back. */
export const FS_REQUEST_ID = /^[A-Za-z0-9_-]{1,32}$/;

/** One entry of a directory listing. */
export interface FsListEntry {
  /** Basename only — never a path. */
  name: string;
  kind: 'file' | 'dir';
  /** Regular files only; directories report 0. */
  size: number;
  mtimeMs: number;
}

/**
 * Whether `value` is one entry name inside a listed directory: a basename of
 * sane length, never a path, never `.`/`..` and without control characters.
 * It is what a download picks and what a listing reports, so both ends check
 * with the same rule.
 */
export function isFsEntryName(value: unknown): value is string {
  return (
    typeof value === 'string' &&
    value.length > 0 &&
    value.length <= FS_NAME_MAX_CHARS &&
    value !== '.' &&
    value !== '..' &&
    !/[\\/]/.test(value) &&
    ![...value].some((ch) => ch.charCodeAt(0) < 32 || ch.charCodeAt(0) === 127)
  );
}

/**
 * Whether `value` may ride on `fs_list_request.dir`: `'.'` re-reads the
 * directory the last listing pinned, `'..'` goes to its parent, and anything
 * else must be one of the names it contained — which `isFsEntryName` rules
 * out for both sentinels, so they can never collide with a real entry.
 */
export function isFsListDir(value: unknown): value is string {
  return value === '.' || value === '..' || isFsEntryName(value);
}

/**
 * The window asks what the terminal's working directory holds. `dir` moves
 * the listing relative to the last one this stream was given: `'.'` re-reads
 * it, `'..'` steps up to its parent, another value names a directory it
 * contained. Omitted, the host resolves the terminal's own directory.
 */
export interface ClientFsListRequestMessage {
  type: 'fs_list_request';
  requestId: string;
  dir?: string;
}

/**
 * Download the named entries of the directory the last `fs_list_response`
 * reported. One file comes as itself; anything more, or any directory, arrives
 * as a zip the workstation built.
 */
export interface ClientFsDownloadRequestMessage {
  type: 'fs_download_request';
  requestId: string;
  names: string[];
}

/** One slice of a transfer the workstation announced, by index. */
export interface ClientFsDownloadChunkRequestMessage {
  type: 'fs_download_chunk_request';
  requestId: string;
  index: number;
}

/** Show the text of a listed file — the workstation reads it, not the window. */
export interface ClientFsPreviewRequestMessage {
  type: 'fs_preview_request';
  requestId: string;
  name: string;
}

/** Give a listed entry a new name inside the same directory. */
export interface ClientFsRenameRequestMessage {
  type: 'fs_rename_request';
  requestId: string;
  name: string;
  newName: string;
}

/** Remove a listed entry; a directory goes away with everything inside it. */
export interface ClientFsDeleteRequestMessage {
  type: 'fs_delete_request';
  requestId: string;
  name: string;
}

/** The directory's entries; `cwd` is where they were listed, for display. */
export interface ServerFsListResponseMessage {
  type: 'fs_list_response';
  requestId: string;
  cwd: string;
  entries: FsListEntry[];
}

/**
 * A transfer is staged and may be pulled: `totalChunks` slices of
 * `FS_DOWNLOAD_CHUNK_BYTES` (the last short), `size` bytes in all. `name` is
 * the download's suggested file name — the file's own for one file, a zip's
 * for anything else.
 */
export interface ServerFsDownloadReadyMessage {
  type: 'fs_download_ready';
  requestId: string;
  name: string;
  size: number;
  totalChunks: number;
}

/** One slice of a staged transfer. */
export interface ServerFsDownloadChunkMessage {
  type: 'fs_download_chunk';
  requestId: string;
  index: number;
  dataBase64: string;
}

/**
 * The file's text, as much as fits `FS_PREVIEW_MAX_BYTES`; `truncated` marks
 * the file carried on past what was read. Text only — a binary answers with
 * an `fs_not_text` error instead.
 */
export interface ServerFsPreviewResponseMessage {
  type: 'fs_preview_response';
  requestId: string;
  name: string;
  text: string;
  truncated: boolean;
}

/** A rename or delete went through; the window re-reads for fresh entries. */
export interface ServerFsMutationDoneMessage {
  type: 'fs_mutation_done';
  requestId: string;
}

export interface HostFsListResponseMessage extends ServerFsListResponseMessage {
  clientId?: string;
  streamId?: string;
}

export interface HostFsDownloadReadyMessage extends ServerFsDownloadReadyMessage {
  clientId?: string;
  streamId?: string;
}

export interface HostFsDownloadChunkMessage extends ServerFsDownloadChunkMessage {
  clientId?: string;
  streamId?: string;
}

export interface HostFsPreviewResponseMessage extends ServerFsPreviewResponseMessage {
  clientId?: string;
  streamId?: string;
}

export interface HostFsMutationDoneMessage extends ServerFsMutationDoneMessage {
  clientId?: string;
  streamId?: string;
}

export interface RelayFsListRequestMessage extends ClientFsListRequestMessage {
  clientId?: string;
  streamId?: string;
}

export interface RelayFsDownloadRequestMessage extends ClientFsDownloadRequestMessage {
  clientId?: string;
  streamId?: string;
}

export interface RelayFsDownloadChunkRequestMessage extends ClientFsDownloadChunkRequestMessage {
  clientId?: string;
  streamId?: string;
}

export interface RelayFsPreviewRequestMessage extends ClientFsPreviewRequestMessage {
  clientId?: string;
  streamId?: string;
}

export interface RelayFsRenameRequestMessage extends ClientFsRenameRequestMessage {
  clientId?: string;
  streamId?: string;
}

export interface RelayFsDeleteRequestMessage extends ClientFsDeleteRequestMessage {
  clientId?: string;
  streamId?: string;
}

/** Every fs request a host may be handed, after the relay stamped its stream. */
export type RelayFsRequestMessage =
  | RelayFsListRequestMessage
  | RelayFsDownloadRequestMessage
  | RelayFsDownloadChunkRequestMessage
  | RelayFsPreviewRequestMessage
  | RelayFsRenameRequestMessage
  | RelayFsDeleteRequestMessage;
